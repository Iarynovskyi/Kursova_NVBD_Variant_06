DECLARE @Attempt INT = 0, @Bad INT = 1;
WHILE @Attempt < 4 AND @Bad > 0
BEGIN
    -- Призначення речовини за протоколом та конкретного препарату
    UPDATE rx SET SubstID = t.SubstID,
                  MedicationID = (SELECT ms.MedicationID FROM #MedBySubst ms
                                  WHERE ms.SubstID = t.SubstID AND ms.Rn = 1 + (CAST(rx.r2 AS BIGINT) + @Attempt * 7919) % ms.Cnt)
    FROM #Rx rx
    JOIN #RefTherapy t ON t.DiseaseID = rx.DiseaseID AND t.SlotIdx = rx.SlotIdx
    WHERE rx.MedicationID IS NULL;

    -- Виявлення небезпечних призначень (алергія або абсолютне протипоказання)
    UPDATE rx SET SlotIdx = (rx.SlotIdx + 1) % rx.TCnt, MedicationID = NULL, SubstID = NULL
    FROM #Rx rx
    WHERE EXISTS (SELECT 1 FROM dbo.PatientContraindications pc WHERE pc.PatientID = rx.PatientID AND pc.MedicationID = rx.MedicationID)
       OR EXISTS (SELECT 1 FROM #AbsRule ar
                  WHERE ar.SubstID = rx.SubstID
                    AND (ar.DiseaseID = rx.DiseaseID
                         OR EXISTS (SELECT 1 FROM #PatRisk pr WHERE pr.PatientID = rx.PatientID AND pr.DiseaseID = ar.DiseaseID)));
    SET @Bad = @@ROWCOUNT;
    PRINT N'   Спроба ' + CAST(@Attempt + 1 AS NVARCHAR(5)) + N': замінено небезпечних призначень — ' + CAST(@Bad AS NVARCHAR(10));
    SET @Attempt += 1;
END

