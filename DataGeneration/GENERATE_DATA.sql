;WITH prim AS (
    SELECT v.VisitID, v.VisitKey, v.PatientID, v.VisitDate, v.AgeAtVisit, v.Purpose, d.DiseaseID, d.IsChronic, d.CatCode,
           d.RecMin, d.RecMax, d.SickPct, d.SevLvl,
           r.r1, r.r2, r.r3, r.r4, r.r5, r.r6,
           ROW_NUMBER() OVER (PARTITION BY v.PatientID, v.DiseaseID ORDER BY v.VisitDateTime, v.VisitKey) AS RnDis
    FROM #V v
    JOIN #RefDisease d ON d.DiseaseID = v.DiseaseID
    CROSS APPLY dbo.gen_Rnd('DG', v.VisitKey) r
), sev AS (
    SELECT p.*,
        CASE WHEN p.CatCode = 'ZZZ' THEN N'Легка'
             ELSE CASE p.SevLvl
                 WHEN 1 THEN CASE WHEN p.r1 % 1000 < 650 THEN N'Легка' WHEN p.r1 % 1000 < 950 THEN N'Середня' WHEN p.r1 % 1000 < 995 THEN N'Тяжка' ELSE N'Критична' END
                 WHEN 2 THEN CASE WHEN p.r1 % 1000 < 350 THEN N'Легка' WHEN p.r1 % 1000 < 800 THEN N'Середня' WHEN p.r1 % 1000 < 970 THEN N'Тяжка' ELSE N'Критична' END
                 ELSE        CASE WHEN p.r1 % 1000 < 100 THEN N'Легка' WHEN p.r1 % 1000 < 500 THEN N'Середня' WHEN p.r1 % 1000 < 880 THEN N'Тяжка' ELSE N'Критична' END
             END END AS Severity,
        CASE WHEN p.CatCode <> 'ZZZ' AND p.r2 % 100 < 4 THEN DATEADD(DAY, 1 + p.r2 % 2, p.VisitDate) ELSE p.VisitDate END AS DiagnosisDate
    FROM prim p
), plan_ AS (
    SELECT s.*,
        CASE WHEN s.CatCode = 'ZZZ' THEN 0
             ELSE CAST(ROUND((s.RecMin + s.r3 % (s.RecMax - s.RecMin + 1))
                  * CASE s.Severity WHEN N'Легка' THEN 0.8 WHEN N'Середня' THEN 1.0 WHEN N'Тяжка' THEN 1.4 ELSE 1.8 END, 0) AS INT)
        END AS PlannedDays
    FROM sev s
), outc AS (
    SELECT pl.*,
        CASE
            WHEN pl.CatCode = 'ZZZ' THEN N'Без змін'
            WHEN DATEADD(DAY, pl.PlannedDays, pl.DiagnosisDate) > '2025-12-31' THEN N'В процесі'
            WHEN pl.IsChronic = 1 AND pl.RnDis = 1 AND pl.r4 % 100 < 60 THEN N'Хронізація'
            WHEN pl.IsChronic = 1 THEN
                CASE pl.Severity
                    WHEN N'Критична' THEN CASE WHEN pl.r4 % 100 < 50 THEN N'Направлено в стаціонар' WHEN pl.r4 % 100 < 80 THEN N'Ускладнення' ELSE N'Покращення' END
                    WHEN N'Тяжка'    THEN CASE WHEN pl.r4 % 100 < 12 THEN N'Направлено в стаціонар' WHEN pl.r4 % 100 < 27 THEN N'Ускладнення' WHEN pl.r4 % 100 < 77 THEN N'Покращення' ELSE N'Без змін' END
                    ELSE                  CASE WHEN pl.r4 % 100 < 55 THEN N'Покращення' WHEN pl.r4 % 100 < 95 THEN N'Без змін' ELSE N'Ускладнення' END
                END
            ELSE
                CASE pl.Severity
                    WHEN N'Критична' THEN CASE WHEN pl.r4 % 100 < 55 THEN N'Направлено в стаціонар' WHEN pl.r4 % 100 < 70 THEN N'Ускладнення' WHEN pl.r4 % 100 < 85 THEN N'Покращення' ELSE N'Одужання' END
                    WHEN N'Тяжка'    THEN CASE WHEN pl.r4 % 100 < 15 THEN N'Направлено в стаціонар' WHEN pl.r4 % 100 < 25 THEN N'Ускладнення' WHEN pl.r4 % 100 < 55 THEN N'Покращення' ELSE N'Одужання' END
                    WHEN N'Середня'  THEN CASE WHEN pl.r4 % 100 < 2 THEN N'Направлено в стаціонар' WHEN pl.r4 % 100 < 7 THEN N'Ускладнення' WHEN pl.r4 % 100 < 10 THEN N'Хронізація'
                                               WHEN pl.r4 % 100 < 30 THEN N'Покращення' WHEN pl.r4 % 100 < 33 THEN N'Без змін' ELSE N'Одужання' END
                    ELSE                  CASE WHEN pl.r4 % 100 < 85 THEN N'Одужання' WHEN pl.r4 % 100 < 97 THEN N'Покращення' ELSE N'Без змін' END
                END
        END AS TreatmentOutcome
    FROM plan_ pl
