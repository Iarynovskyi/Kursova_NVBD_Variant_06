    rx.DiagnosisID, rx.MedicationID,
    CASE ms.Form
        WHEN N'Таблетки' THEN N'По 1 таблетці '
        WHEN N'Капсули'  THEN N'По 1 капсулі '
        WHEN N'Ампули'   THEN N'По 1 ампулі в/м '
        WHEN N'Сироп'    THEN N'По 5 мл '
        WHEN N'Мазь'     THEN N'Наносити тонким шаром '
        WHEN N'Краплі'   THEN N'По 2 краплі '
        WHEN N'Спрей'    THEN N'По 1 дозі '
        ELSE                  N'По 1 саше '
    END + CASE ms.DosesPerDay WHEN 1 THEN N'1 раз' WHEN 5 THEN N'5 разів' ELSE CAST(ms.DosesPerDay AS NVARCHAR(2)) + N' рази' END + N' на добу',
    dur.Days,
    CAST(CASE WHEN q.Qty < 1 THEN 1 WHEN q.Qty > 50 THEN 50 ELSE q.Qty END AS TINYINT),
    CASE WHEN s.SubsFrom IS NOT NULL AND v.VisitDate >= s.SubsFrom AND rx.r3 % 100 < 80 THEN 1 ELSE 0 END,
    DATEADD(MINUTE, v.DurationMinutes - 1, v.VisitDateTime)
