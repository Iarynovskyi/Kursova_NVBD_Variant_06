/* ---------------------------------------------------------------------
   КРОК 14. Рецепти (≈600 000) за протоколами лікування + контроль безпеки BR-1
   --------------------------------------------------------------------- */
DROP TABLE IF EXISTS #TherCnt, #Rx, #PatRisk, #AbsRule;

SELECT DiseaseID, COUNT(*) AS TCnt INTO #TherCnt FROM #RefTherapy GROUP BY DiseaseID;

;WITH k AS (
    SELECT dg.DiagnosisID, dg.PatientID, dg.DiseaseID, dg.DiagnosisDate, dg.IsChronic, dg.PlannedDays, tc.TCnt,
           dg.RxRand % tc.TCnt AS StartIdx,
           CASE WHEN dg.IsPrimary = 1
                THEN CASE WHEN dg.RxRand % 100 < 12 THEN 0 WHEN dg.RxRand % 100 < 62 THEN 1 WHEN dg.RxRand % 100 < 90 THEN 2 ELSE 3 END
                ELSE CASE WHEN dg.RxRand % 100 < 50 THEN 1 ELSE 0 END END AS NRx
    FROM #Dg dg JOIN #TherCnt tc ON tc.DiseaseID = dg.DiseaseID
)
SELECT k.DiagnosisID, k.PatientID, k.DiseaseID, k.DiagnosisDate, k.IsChronic, k.PlannedDays, k.TCnt,
       n.n AS I, (k.StartIdx + n.n - 1) % k.TCnt AS SlotIdx,
       CAST(NULL AS INT) AS SubstID, CAST(NULL AS INT) AS MedicationID,
       r.r1, r.r2, r.r3, r.r4
INTO #Rx
FROM k
JOIN #Numbers n ON n.n <= CASE WHEN k.NRx > k.TCnt THEN k.TCnt ELSE k.NRx END
CROSS APPLY dbo.gen_Rnd('RX', k.DiagnosisID * 10 + n.n) r;

CREATE UNIQUE CLUSTERED INDEX CIX_Rx ON #Rx (DiagnosisID, I);

-- Фактори ризику пацієнта (як у тригері BR-1): хронічні хвороби та незавершені випадки
SELECT DISTINCT dg.PatientID, dg.DiseaseID
INTO #PatRisk
FROM #Dg dg
WHERE dg.IsChronic = 1 OR dg.TreatmentOutcome = N'В процесі';
CREATE UNIQUE CLUSTERED INDEX CIX_PatRisk ON #PatRisk (PatientID, DiseaseID);

SELECT SubstID, DiseaseID INTO #AbsRule FROM #RefRule WHERE Severity = N'Абсолютне';
