/* ---------------------------------------------------------------------
   КРОК 0. Допоміжний генератор псевдовипадкових чисел (inline TVF)
   Повертає 8 незалежних цілих 0..2^31-1 для пари (сіль, номер)
   --------------------------------------------------------------------- */
CREATE OR ALTER FUNCTION dbo.gen_Rnd (@salt VARCHAR(16), @n BIGINT)
RETURNS TABLE
AS
RETURN
    SELECT
        CAST(SUBSTRING(x.h1, 1, 4)  AS INT) & 2147483647 AS r1,
        CAST(SUBSTRING(x.h1, 5, 4)  AS INT) & 2147483647 AS r2,
        CAST(SUBSTRING(x.h1, 9, 4)  AS INT) & 2147483647 AS r3,
        CAST(SUBSTRING(x.h1, 13, 4) AS INT) & 2147483647 AS r4,
        CAST(SUBSTRING(x.h2, 1, 4)  AS INT) & 2147483647 AS r5,
        CAST(SUBSTRING(x.h2, 5, 4)  AS INT) & 2147483647 AS r6,
        CAST(SUBSTRING(x.h2, 9, 4)  AS INT) & 2147483647 AS r7,
        CAST(SUBSTRING(x.h2, 13, 4) AS INT) & 2147483647 AS r8
    FROM (SELECT HASHBYTES('MD5', CONCAT(@salt, '|', @n)) AS h1,
                 HASHBYTES('MD5', CONCAT(@salt, '#', @n)) AS h2) AS x;
GO

